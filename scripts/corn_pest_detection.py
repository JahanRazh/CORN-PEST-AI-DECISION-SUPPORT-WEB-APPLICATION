import os
import json
import numpy as np
import tensorflow as tf
import matplotlib.pyplot as plt
import matplotlib.image as mpimg

# ==========================================================
# SETTINGS
# ==========================================================
MODEL_FOLDER = "/content/drive/MyDrive/corn_pest/models"
IMAGE_SIZE = 224

best_model_path = os.path.join(MODEL_FOLDER, "best_corn_pest_model.keras")
class_names_path = os.path.join(MODEL_FOLDER, "class_names.json")

# ==========================================================
# GET THE TEST IMAGE
# ==========================================================
from google.colab import files

print("Please choose an image file to upload...")
uploaded = files.upload()

# Grab the first (and normally only) uploaded file
IMAGE_PATH = "/content/drive/MyDrive/corn_pest/test_photo.jpg" + list(uploaded.keys())[0]

# ==========================================================
# CHECK MODEL + IMAGE EXIST
# ==========================================================
if not os.path.exists(best_model_path):
    raise FileNotFoundError(
        f"Model not found: {best_model_path}\n"
        "Make sure you already ran the training script and that "
        "MODEL_FOLDER above matches the training script's MODEL_FOLDER."
    )

if not os.path.exists(IMAGE_PATH):
    raise FileNotFoundError(f"Image not found: {IMAGE_PATH}")

# ==========================================================
# LOAD MODEL + CLASS NAMES
# ==========================================================
print("\nLoading model...")
model = tf.keras.models.load_model(best_model_path)

with open(class_names_path, "r", encoding="utf-8") as file:
    CLASS_NAMES = json.load(file)

# ==========================================================
# LOAD + PREPROCESS THE IMAGE
# ==========================================================
img = tf.keras.utils.load_img(
    IMAGE_PATH,
    target_size=(IMAGE_SIZE, IMAGE_SIZE)
)

img_array = tf.keras.utils.img_to_array(img)
img_array = np.expand_dims(img_array, axis=0)  # shape: (1, 224, 224, 3)

# ==========================================================
# PREDICT
# ==========================================================
predictions = model.predict(img_array, verbose=0)
probabilities = predictions[0]

predicted_index = np.argmax(probabilities)
predicted_class = CLASS_NAMES[predicted_index]
confidence = probabilities[predicted_index] * 100

# ==========================================================
# SHOW THE IMAGE
# ==========================================================
plt.figure(figsize=(5, 5))
plt.imshow(mpimg.imread(IMAGE_PATH))
plt.axis("off")
plt.title(f"{predicted_class} ({confidence:.2f}%)")
plt.show()

# ==========================================================
# SHOW RESULT
# ==========================================================
print("\n" + "="*60)
print("PREDICTION RESULT")
print("="*60)
print(f"Image        : {IMAGE_PATH}")
print(f"Predicted    : {predicted_class}")
print(f"Confidence   : {confidence:.2f}%")

print("\nAll class probabilities:")
print("-"*60)
sorted_indices = np.argsort(probabilities)[::-1]
for i in sorted_indices:
    print(f"{CLASS_NAMES[i]:40s} : {probabilities[i]*100:.2f}%")